def make_font(dest):
    """GRUB needs .pf2; bake one from the first font we can find."""
    src = next((f for f in FONT_CANDIDATES if os.path.exists(f)), None)
    tool = shutil.which("grub2-mkfont") or shutil.which("grub-mkfont")
    if not src or not tool:
        return []
    made = []
    for size in SIZES:
        out = os.path.join(dest, f"{SLUG.lower()}-{size}.pf2")
        r = subprocess.run([tool, "-s", str(size), "-n", f"{FONT_NAME} {size}", "-o", out, src],
                           capture_output=True, text=True)
        if r.returncode == 0:
            made.append(os.path.basename(out))
    return made


def build(out_root, night):
    base = os.path.join(out_root, "grub", "themes", IDS["plymouth"])
    if os.path.exists(base):
        shutil.rmtree(base)
    os.makedirs(base)
    background(night).save(os.path.join(base, "background.png"))
    p = DARK
    art = {}
    art.update(nine_slice("select", p["accent"], radius=10, alpha=70, border=p["accent"]))
    art.update(nine_slice("thumb", p["accent"], radius=3, alpha=180))
    art.update(nine_slice("track", p["border"], radius=3, alpha=140))
    art.update(nine_slice("fill", p["accent"], radius=3, alpha=255))
    for name, img in art.items():
        img.save(os.path.join(base, name))
    with open(os.path.join(base, "theme.txt"), "w") as f:
        f.write(theme_txt())
    fonts = make_font(base)
    if not fonts:
        print("  (no grub2-mkfont or font file: the menu will use GRUB's built-in font)")
    return base


