"""Borealis for the GRUB menu — the last stock-looking screen before Plasma.

Renders the aurora as the menu background, a rounded accent highlight for the
selected entry, and bakes a .pf2 font (GRUB can't read TTFs). Installed by
`install-system.sh --grub`, which also switches GRUB to graphics mode.
"""
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(__file__))
from tokens import DARK, IDS, NAME, SLUG, mix, rgb  # noqa: E402

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter  # noqa: E402

W, H = 1920, 1200
FONT_CANDIDATES = [
    "/usr/share/fonts/rsms-inter-fonts/Inter-Regular.ttf",
    "/usr/share/fonts/rsms-inter-fonts/Inter-Medium.ttf",
    "/usr/share/fonts/abattis-cantarell-vf-fonts/Cantarell-VF.otf",
    "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf",
]
FONT_NAME = f"{NAME} Regular"
SIZES = (20, 28)          # menu entries, title


def background(night):
    """The aurora, dimmed and blurred a little so menu text stays readable."""
    img = night.convert("RGB").resize((W, H), Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(3))
    img = ImageEnhance.Brightness(img).enhance(0.55)
    shade = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(shade)
    for i in range(H):                      # darker towards the middle rows
        d.line([(0, i), (W, i)], fill=int(90 * min(1.0, abs(i / H - 0.5) * 2) ** 2))
    return Image.composite(img, ImageEnhance.Brightness(img).enhance(1.25), shade)


def nine_slice(base, color, radius=10, alpha=210, border=None):
    """Write <base>_{c,n,s,e,w,ne,nw,se,sw}.png for a rounded pixmap style."""
    size = radius * 2 + 2
    tile = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(tile)
    d.rounded_rectangle([0, 0, size - 1, size - 1], radius=radius,
                        fill=rgb(color) + (alpha,),
                        outline=(rgb(border) + (255,)) if border else None,
                        width=2 if border else 0)
    r = radius
    pieces = {
        "nw": (0, 0, r, r), "n": (r, 0, r + 1, r), "ne": (size - r, 0, size, r),
        "w": (0, r, r, r + 1), "c": (r, r, r + 1, r + 1), "e": (size - r, r, size, r + 1),
        "sw": (0, size - r, r, size), "s": (r, size - r, r + 1, size),
        "se": (size - r, size - r, size, size),
    }
    out = {}
    for name, box in pieces.items():
        out[f"{base}_{name}.png"] = tile.crop(box)
    return out


